// Generates worker/generated.js: the admin page and a snapshot of the site's categories/taxonomy,
// bundled into the Worker so the admin needs no extra storage. Runs as part of `npm run build:cloudflare`.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadConfig } from './lib/config.mjs';

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const json = (rel, fallback) => (fs.existsSync(path.join(ROOT, rel)) ? JSON.parse(read(rel)) : fallback);
const snapshot = {
  brand: loadConfig().brand?.name || 'Promptrin',
  taxonomy: json('data/taxonomy.json', {}),
  categories: json('data/categories.json', []),
  redirects: json('data/redirects.json', []),
};
const out = `// GENERATED by scripts/build-worker-assets.mjs. Do not edit by hand.
export const ADMIN_HTML = ${JSON.stringify(read('admin/panel.html'))};
export const SNAPSHOT = ${JSON.stringify(snapshot)};
`;
fs.writeFileSync(path.join(ROOT, 'worker/generated.js'), out);
console.log(`worker/generated.js written (${(out.length / 1024).toFixed(0)} KB)`);
